// Discovers the catalogues in src/i18n/locales and writes the language list the app loads from (UI-GUIDELINES §11b).
//   node scripts/i18n.mjs            write src/i18n/generated/languages.ts
//   node scripts/i18n.mjs --check    fail when the generated list is stale (part of pnpm check)
//   node scripts/i18n.mjs --report   list missing and unknown keys per language; never fails the build
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { AREAS, areaKeys, selfTest } from "./i18n-areas.mjs";

const LOCALES = join("src", "i18n", "locales");
const OUTPUT = join("src", "i18n", "generated", "languages.ts");
const REFERENCE = "en";

function load(code) {
  const value = JSON.parse(readFileSync(join(LOCALES, `${code}.json`), "utf8"));
  if (typeof value.language !== "string" || typeof value.messages !== "object")
    throw new Error(`${code}.json needs "language" and "messages"`);
  return value;
}

const codes = readdirSync(LOCALES)
  .filter((name) => name.endsWith(".json"))
  .map((name) => name.slice(0, -".json".length))
  .sort((a, b) =>
    a === REFERENCE ? -1 : b === REFERENCE ? 1 : a.localeCompare(b),
  );
const catalogues = Object.fromEntries(codes.map((code) => [code, load(code)]));
const referenceKeys = Object.keys(catalogues[REFERENCE].messages);
/** The reference messages a language does not translate; none means the language is complete. */
const missingIn = (code) =>
  referenceKeys.filter(
    (key) => typeof catalogues[code].messages[key] !== "string",
  );

if (process.argv.includes("--report")) {
  const keys = referenceKeys;
  for (const code of codes.filter((code) => code !== REFERENCE)) {
    const messages = catalogues[code].messages;
    const missing = missingIn(code);
    const unknown = Object.keys(messages).filter((key) => !keys.includes(key));
    const status = catalogues[code].status
      ? ` [${catalogues[code].status}]`
      : "";
    console.log(
      `${code} (${catalogues[code].language})${status}: ${keys.length - missing.length}/${keys.length} translated` +
        (missing.length ? `; missing: ${missing.join(", ")}` : "") +
        (unknown.length ? `; unknown: ${unknown.join(", ")}` : ""),
    );
  }
} else {
  const lines = [
    "// Generated by scripts/i18n.mjs from src/i18n/locales/*.json; do not edit. Run `pnpm i18n:gen` after adding a language.",
    "",
    "/** Every shipped language: its code, its name in its own script, and whether it translates every message. */",
    "export const LANGUAGES = [",
    ...codes.map(
      (code) =>
        `  { code: ${JSON.stringify(code)}, name: ${JSON.stringify(catalogues[code].language)}, complete: ${missingIn(code).length === 0} },`,
    ),
    "] as const;",
    "",
    "/** Loads a non-reference catalogue on demand, so only the chosen language is downloaded. */",
    "export const CATALOGUES: Readonly<Record<string, () => Promise<unknown>>> = {",
    ...codes
      .filter((code) => code !== REFERENCE)
      .map(
        (code) =>
          `  ${JSON.stringify(code)}: () => import("../locales/${code}.json"),`,
      ),
    "};",
    "",
  ];
  const outputs = [[OUTPUT, lines.join("\n")], ...splitCatalogue()];
  if (process.argv.includes("--check")) {
    selfTest();
    const stale = outputs.filter(([path, content]) => {
      try {
        return readFileSync(path, "utf8") !== content;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(
        `Stale: ${stale.map(([path]) => path).join(", ")}; run pnpm i18n:gen`,
      );
      process.exitCode = 1;
    } else
      console.log(
        `Language list and catalogue split are current: ${codes.join(", ")}.`,
      );
  } else {
    mkdirSync(join("src", "i18n", "generated"), { recursive: true });
    for (const [path, content] of outputs) writeFileSync(path, content);
    console.log(`Wrote ${outputs.map(([path]) => path).join(", ")}.`);
  }
}

/** Product source for the split: no tests, no generated code, no test helpers or catalogues. */
function productSource(directory = "src", files = new Map()) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) {
      if (!["generated", "test", "locales"].includes(entry.name))
        productSource(path, files);
    } else if (/\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name))
      files.set(path, readFileSync(path, "utf8"));
  }
  return files;
}

/** English split by use: the core catalogue every page loads and each area's own (WEB-U-014). */
function splitCatalogue() {
  const source = productSource();
  const owner = new Map(
    AREAS.flatMap((area) =>
      areaKeys(source, referenceKeys, area).map((key) => [key, area.name]),
    ),
  );
  const part = (area) =>
    Object.fromEntries(
      Object.entries(catalogues[REFERENCE].messages).filter(
        ([key]) => (owner.get(key) ?? "core") === area,
      ),
    );
  const file = (name, messages) => [
    join("src", "i18n", "generated", name),
    JSON.stringify(
      { language: catalogues[REFERENCE].language, messages },
      null,
      2,
    ) + "\n",
  ];
  return ["core", ...AREAS.map((area) => area.name)].map((area) =>
    file(`en.${area}.json`, part(area)),
  );
}
