import { createHash } from "node:crypto";

import { format } from "prettier";

const annotations = new Set([
  "$schema",
  "$id",
  "title",
  "description",
  "default",
  "examples",
  "deprecated",
  "readOnly",
  "writeOnly",
  "format",
  "pattern",
  "minimum",
  "maximum",
  "exclusiveMinimum",
  "exclusiveMaximum",
  "multipleOf",
  "minLength",
  "maxLength",
  "minItems",
  "maxItems",
  "uniqueItems",
  "minProperties",
  "maxProperties",
]);
const shapes = new Set([
  "$ref",
  "type",
  "const",
  "enum",
  "oneOf",
  "anyOf",
  "allOf",
  "not",
  "properties",
  "required",
  "additionalProperties",
  "propertyNames",
  "items",
]);

function reference(value) {
  const name = value.split("/").at(-1);
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name ?? ""))
    throw new Error("Invalid type reference");
  if (
    value.startsWith("#/definitions/") ||
    value.startsWith("#/components/schemas/")
  )
    return name;
  if (value.includes("tqa-protocol-v1.json#/definitions/"))
    return `Protocol.${name}`;
  throw new Error("Unsupported external type reference");
}

function expression(schema, inheritedType) {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  for (const key of Object.keys(schema)) {
    if (!annotations.has(key) && !shapes.has(key))
      throw new Error(`Unsupported schema keyword: ${key}`);
  }
  // Runtime validation enforces negation; structural types cannot express a negated pattern.
  if ("not" in schema) {
    if (schema.not === true) return "never";
    expression(schema.not);
  }
  // Keys are strings either way; runtime validation enforces the key rule.
  if (schema.propertyNames && typeof schema.propertyNames === "object")
    expression(schema.propertyNames, "string");
  if (schema.$ref) return reference(schema.$ref);
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum)
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  const type = schema.type ?? inheritedType;
  const parts = [];
  for (const key of ["oneOf", "anyOf", "allOf"])
    if (schema[key])
      parts.push(
        `(${schema[key].map((branch) => expression(branch, type)).join(key === "allOf" ? " & " : " | ")})`,
      );
  const shape = shapeExpression(schema, type);
  if (shape !== "unknown") parts.push(shape);
  return parts.length ? parts.join(" & ") : "unknown";
}

// Applicator branches refine their sibling shape; they never replace its required fields.
function shapeExpression(schema, type) {
  if (Array.isArray(type))
    return `(${type.map((part) => shapeExpression(schema, part)).join(" | ")})`;
  switch (type) {
    case "string":
      return "string";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "integer":
    case "number":
      return "number";
    case "array":
      // A draft-7 tuple lists one schema per position; its length is enforced at the runtime boundary.
      if (Array.isArray(schema.items))
        return `[${schema.items.map((item) => expression(item)).join(", ")}]`;
      return `Array<${expression(schema.items ?? true)}>`;
    case "object": {
      const properties = Object.entries(schema.properties ?? {}).map(
        ([name, value]) => {
          const optional = schema.required?.includes(name) ? "" : "?";
          return `${JSON.stringify(name)}${optional}: ${expression(value)};`;
        },
      );
      if (
        schema.additionalProperties &&
        typeof schema.additionalProperties === "object"
      )
        properties.push(
          `[key: string]: ${expression(schema.additionalProperties)};`,
        );
      return properties.length
        ? `{${properties.join("\n")}}`
        : `Record<string, ${schema.additionalProperties === false ? "never" : "unknown"}>`;
    }
    case undefined:
      return "unknown";
    default:
      throw new Error(`Unsupported schema type: ${type}`);
  }
}

export async function generate(schema, isApi = false) {
  const definitions = isApi ? schema.components.schemas : schema.definitions;
  if (!definitions) throw new Error("Missing schema definitions");
  const hash = createHash("sha256")
    .update(JSON.stringify(schema))
    .digest("hex");
  const header = `// Generated by scripts/protocol.mjs. Do not edit.\n// Source SHA-256: ${hash}\n`;
  const imports = isApi ? 'import type * as Protocol from "./protocol";\n' : "";
  const types = Object.entries(definitions)
    .map(([name, value]) => {
      if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name))
        throw new Error("Invalid definition name");
      return `export type ${name} = ${expression(value)};`;
    })
    .join("\n\n");
  const map = isApi
    ? `\nexport type Schemas = {${Object.keys(definitions)
        .map((name) => `${name}: ${name};`)
        .join("\n")}};`
    : "";
  return format(header + imports + types + map, { parser: "typescript" });
}
