#!/usr/bin/env python3
"""Generate the Workstation image's package inventory from its installed metadata."""
import argparse
import re
from pathlib import Path
import subprocess
import sys
from urllib.parse import quote

# The release SBOM library (tools/release/sbom_sources.py): beside this script in the image, under tools/ in the
# repository.
HERE = Path(__file__).resolve().parent
for library in (HERE, HERE.parents[1] / "tools" / "release"):
    if (library / "sbom_sources.py").is_file():
        sys.path.insert(0, str(library))
        break
import sbom_sources as sources  # noqa: E402

NPM_DIRS = ("usr/local/lib/node_modules", "usr/local/lib/tqa/browser/node_modules")


def command(*arguments):
    return subprocess.check_output(arguments, text=True, timeout=60).strip()


def cell(text):
    return str(text).replace("|", "&#124;").replace("\n", " ").replace("\r", " ")


def debian_rows(root):
    rows = []
    for package in sources.debian_packages(root):
        copyright_url = "https://sources.debian.org/src/{}/{}/debian/copyright/".format(
            quote(package.source_name), quote(package.source_version))
        rows.append("| {} | {} | {} | [copyright]({}) · [source]({}) |".format(
            cell(package.name), cell(package.version), cell(package.license), copyright_url,
            package.download_location))
    return sorted(rows)


def node_rows(root):
    return sorted({"| {} | {} | {} | [source]({}) |".format(
        cell(package.name), cell(package.version), cell(package.license), package.download_location)
        for package in sources.npm_packages(root, NPM_DIRS)})


def snapshot(root):
    """The Debian snapshot the image's apt sources pin (images/runtime/Dockerfile); the Dockerfile is the one place
    the date is written."""
    text = (Path(root) / "etc/apt/sources.list").read_text(encoding="utf-8")
    dates = set(re.findall(r"snapshot\.debian\.org/archive/debian(?:-security)?/(\d{8}T\d{6}Z)/", text))
    if len(dates) != 1:
        raise SystemExit("the image's apt sources pin no single Debian snapshot")
    return dates.pop()


def inventory():
    origin = Path("/usr/share/tqa/node-origin.txt").read_text(encoding="utf-8").strip()
    node_version = command("node", "--version").removeprefix("v")
    go_version = command("/usr/local/go/bin/go", "version").split()[2].removeprefix("go")
    return "\n".join([
        "# Workstation runtime image packages", "",
        "Generated by `python3 images/runtime/packages.py`; do not edit by hand.", "",
        "Architecture: `{}`. Debian snapshot: `{}`.".format(command("dpkg", "--print-architecture"), snapshot("/")),
        "Node source image: `{}`.".format(origin), "",
        "Distribution programs are separate image aggregates under ADR-0017. The licence column is the exact SPDX",
        "expression of a machine-readable copyright file, or `LicenseRef-debian-<package>` for the package's own",
        "notice; a licence is never guessed. The linked copyright files and the notices in the image are authoritative.",
        "Exact source versions are linked for release publication; no package source is vendored here.", "",
        "## Debian packages", "",
        "| Package | Installed version | Licence labels | Notices and matching source |",
        "| --- | --- | --- | --- |",
        *debian_rows(Path("/")), "",
        "## Node runtime and npm packages", "",
        "Node's full notice is retained at `/usr/share/doc/node/LICENSE`; it includes notices",
        "for libraries embedded in the binary. Bundled npm package notices remain beside their package metadata.", "",
        "Playwright and playwright-core use the image's npm lockfile, including SHA-512 integrity checks.",
        "Their LICENSE and ThirdPartyNotices.txt files remain in the installed packages.", "",
        "| Package | Version | Licence | Matching source |", "| --- | --- | --- | --- |",
        "| Node.js | {} | MIT and bundled third-party notices | [source](https://nodejs.org/dist/v{}/node-v{}.tar.xz) |".format(node_version, node_version, node_version),
        *node_rows(Path("/")), "",
        "## Go toolchain", "",
        "The official release archive, verified by the SHA-256 go.dev publishes; its notice is retained at",
        "`/usr/share/doc/go/LICENSE`.", "",
        "| Package | Version | Licence | Matching source |", "| --- | --- | --- | --- |",
        "| Go | {} | BSD-3-Clause | [source](https://go.dev/dl/go{}.src.tar.gz) |".format(go_version, go_version), "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inside", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--image", default="tqa-runtime:workstation")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.inside:
        print(inventory(), end="")
        return
    output = command("docker", "run", "--rm", "--network=none", "--read-only",
                     "--cap-drop=ALL", "--security-opt=no-new-privileges:true",
                     "--entrypoint=python3", args.image, "/usr/local/lib/tqa/packages.py", "--inside") + "\n"
    destination = Path(__file__).with_name("PACKAGES.md")
    if args.check:
        if destination.read_text(encoding="utf-8") != output:
            raise SystemExit("PACKAGES.md differs from the installed image; regenerate it")
        print("PACKAGES.md matches the installed image")
    else:
        destination.write_text(output, encoding="utf-8")
        print("Generated images/runtime/PACKAGES.md")


if __name__ == "__main__":
    main()
